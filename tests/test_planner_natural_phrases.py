from datetime import datetime

import pytest

from modules.planner.models import Intent
from modules.planner.parser import PlannerParser


NOW = datetime(2026, 9, 2, 12, 0)


@pytest.mark.parametrize(
    "phrase",
    [
        "Завтра в 15 позвонить Ивану",
        "В пятницу встреча с клиентом в 10:30",
        "Позвонить Петрову в 16:00",
        "Послезавтра подготовить отчёт",
        "В 9 утра отправить документы",
        "Напомни через два часа проверить почту",
        "На следующей неделе встретиться с Иваном",
        "Встреча с клиентом 7 сентября в 14",
        "Сегодня вечером совещание команды",
        "Совещание команды завтра после обеда",
        "Через три часа напомни выключить духовку",
        "Напомни через полчаса позвонить маме",
        "В следующий понедельник в 9 созвон на 30 минут",
        "Во вторник в 18.30 встреча с подрядчиком",
        "Поездка 30 декабря 2026 в 07:15",
        "5 января утром встреча с врачом",
        "Нужно купить билеты",
        "До пятницы подготовить отчёт",
        "Завтра проверить договор",
        "Вечером позвонить клиенту",
        "Создай встречу 02.09.2027 в 16:00 с Анной",
        "Совещание в четверг с 10 до 12",
        "Напомнить завтра в 8 утра принять лекарство",
        "В воскресенье ночью вылет",
        "Оплатить счёт 15 сентября",
    ],
)
def test_natural_phrase_is_recognized(phrase):
    result = PlannerParser().parse(phrase, NOW)
    assert result.intent != Intent.UNKNOWN
    assert result.title
